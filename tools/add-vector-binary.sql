-- Двоичный вектор лица рядом с текстовым (задача #268).
--
-- Зачем: вектор в базе лежит текстом, 512 чисел через вертикальную черту —
-- это около 10 064 байт на лицо, то есть 1 036 МБ на проект из 107 958
-- лиц. Тот же набор во float32 занимает 211 МБ, в 4,9 раза меньше.
-- Проверено на жив��й базе 2026-10-08.
--
-- Идемпотентно: повторный запуск ничего не делает.
--
-- ВНИМАНИЕ. Скрипт только добавляет колонку и НИЧЕГО не переписывает.
-- Перезапись данных делает отдельный шаг (VectorBinMigration), и она
-- обязана проверять каждую строку по содержимому: правило 2.9 появилось
-- из-за аварии, где векторы стёрлись у 7 597 лиц и заметить это было
-- нечем. «Строки переписаны» доказательством не является.

ALTER TABLE tbl_faces ADD COLUMN IF NOT EXISTS vector_bin bytea;

COMMENT ON COLUMN tbl_faces.vector_bin IS
    'Вектор лица как 512 float32 little-endian подряд, 2048 байт. Заполняется миграцией #268, читается только после её проверки.';

